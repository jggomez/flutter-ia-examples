"""Copies the v1.0 catalog (the source of truth) to the agent and the Flutter app.

Run after editing `contracts/snap_sell_catalog.json` or `contracts/examples/`:

    cd agent && uv run python ../contracts/tools/sync_contract.py
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path

CONTRACTS_DIR = Path(__file__).resolve().parent.parent
DART_CONTRACT = (
    CONTRACTS_DIR / ".." / "mobile" / "lib" / "ui" / "catalog" / "snap_sell_contract.g.dart"
)
AGENT_CONTRACTS = CONTRACTS_DIR / ".." / "agent" / "contracts"


def write_dart_contract(catalog: dict) -> None:
    """Embeds the catalog in the Flutter app so renderer and agent share one schema."""
    body = json.dumps(catalog, indent=2, ensure_ascii=False)
    assert "'''" not in body
    DART_CONTRACT.write_text(
        "// GENERATED by contracts/tools/sync_contract.py. Do not edit by hand.\n"
        "// The A2UI v1.0 Snap & Sell catalog, shared with the agent.\n"
        "// demo-data: approved — sample names come from the official Basic Catalog instructions.\n"
        "// ignore_for_file: lines_longer_than_80_chars\n\n"
        f"const String snapSellCatalogJson = r'''\n{body}\n''';\n"
    )


def main() -> None:
    catalog = json.loads((CONTRACTS_DIR / "snap_sell_catalog.json").read_text())
    write_dart_contract(catalog)
    # The agent's Docker build context is agent/, so it gets its own copy.
    if AGENT_CONTRACTS.exists():
        shutil.rmtree(AGENT_CONTRACTS)
    shutil.copytree(CONTRACTS_DIR, AGENT_CONTRACTS, ignore=shutil.ignore_patterns("tools"))
    print(f"synced catalog ({len(catalog['components'])} components) to agent and mobile")


if __name__ == "__main__":
    main()
